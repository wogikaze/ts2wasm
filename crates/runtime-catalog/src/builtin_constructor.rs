//! Builtin JavaScript constructor registry.
//!
//! Each entry describes the ECMAScript-facing metadata (`name`, `length`,
//! `prototype`) and whether `[[Construct]]` / `Reflect.construct` should
//! treat the value as a constructor.

use ts2wasm_runtime_abi::ValueTag;

/// Identifies a well-known builtin constructor global.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
#[repr(u16)]
pub enum BuiltinConstructorKind {
    Object,
    Function,
    Boolean,
    Number,
    String,
    Array,
    Date,
    RegExp,
    Map,
    Set,
    WeakMap,
    WeakSet,
    Symbol,
    Promise,
    BigInt,
    Proxy,
    ArrayBuffer,
    SharedArrayBuffer,
    DataView,
    Int8Array,
    Uint8Array,
    Uint8ClampedArray,
    Int16Array,
    Uint16Array,
    Int32Array,
    Uint32Array,
    Float16Array,
    Float32Array,
    Float64Array,
    BigInt64Array,
    BigUint64Array,
    Error,
    EvalError,
    RangeError,
    ReferenceError,
    SyntaxError,
    TypeError,
    URIError,
    AggregateError,
    FinalizationRegistry,
    WeakRef,
    Iterator,
    AsyncIterator,
    SuppressedError,
    DisposableStack,
    AsyncDisposableStack,
}

/// Static metadata for one builtin constructor global.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct BuiltinConstructorSpec {
    pub kind: BuiltinConstructorKind,
    /// ECMAScript `name` property value.
    pub name: &'static str,
    /// ECMAScript `length` property value.
    pub length: u8,
    /// Wasm global holding the constructor's `.prototype` object (without `$`).
    pub prototype_global: Option<&'static str>,
    /// When set, the constructor is also represented as a NUMBER-tagged sentinel.
    pub sentinel_payload: Option<i32>,
    /// Whether `Reflect.construct` / `isConstructor` should succeed.
    pub is_constructable: bool,
}

