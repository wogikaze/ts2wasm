pub fn error_kind_from_sentinel_payload(payload: i32) -> Option<BuiltinConstructorKind> {
    match payload {
        ValueTag::ERROR_PAYLOAD => Some(BuiltinConstructorKind::Error),
        ValueTag::AGGREGATE_ERROR_PAYLOAD => Some(BuiltinConstructorKind::AggregateError),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn all_kinds_have_unique_names() {
        let mut names = std::collections::BTreeSet::new();
        for kind in BuiltinConstructorKind::ALL {
            assert!(names.insert(spec(*kind).name));
        }
    }

    #[test]
    fn error_sentinels_fit_native_error_payload_range() {
        for kind in BuiltinConstructorKind::ALL {
            if let Some(payload) = spec(*kind).sentinel_payload {
                assert!(payload >= ValueTag::NATIVE_ERROR_PAYLOAD_BASE);
                assert!(payload < ValueTag::DIRECT_LOCAL_TOKEN_PAYLOAD_BASE);
            }
        }
    }
}
