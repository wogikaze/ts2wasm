import { isAlpha, isAlphanumeric, isNumeric, isEmail, isURL, isIP, isLowercase, isUppercase, isAscii, isBoolean, isEmpty, isLength, isByteLength, isHexColor, isInt, isFloat, isJSON, isWhitelisted, escape, trim, ltrim, rtrim, matches } from "./validator-lib";

console.log("=== validator tests ===");
