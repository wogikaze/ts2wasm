#!/usr/bin/env python3
"""Generate Rust differential test code from fixture catalog.

Outputs a Rust source file suitable for inclusion in crates/cli/tests/ that
uses the existing assert_fixture_matches_node pattern to run differential
tests (ts2wasm/iwasm vs Node.js) against a specified set of fixtures.

Usage:
  python3 scripts/gen/generate-differential-tests.py               # full catalog
  python3 scripts/gen/generate-differential-tests.py --sample 25   # first 25
  python3 scripts/gen/generate-differential-tests.py --jsonl       # JSONL output mode
  python3 scripts/gen/generate-differential-tests.py --output path # custom output path
  python3 scripts/gen/generate-differential-tests.py --help        # this message

Output:
  By default writes to crates/cli/tests/auto_differential_tests.rs.
  The generated file contains "auto_diff" and "generated_differential" markers.
"""

import argparse
import json
import os
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).parent.parent.parent.resolve()
CATALOG_PATH = REPO_ROOT / "fixtures" / "catalog.yaml"
DEFAULT_OUTPUT = REPO_ROOT / "crates" / "cli" / "tests" / "auto_differential_tests.rs"

# Header template for the generated Rust file
RUST_HEADER = r"""// auto_diff: generated_differential
// This file is auto-generated by scripts/gen/generate-differential-tests.py.
// Do not edit manually. Re-generate with:
//   python3 scripts/gen/generate-differential-tests.py [--sample N]
//
// Generated at: {timestamp}
// Total fixtures: {total}
//

#![allow(clippy::duplicate_mod)]

use std::path::Path;
use std::process::Command;
use std::time::Duration;

#[path = "common/iwasm_runtime.rs"]
mod iwasm_runtime;

#[path = "common/capability.rs"]
mod capability;

use iwasm_runtime::run_iwasm_with_timeout_duration;
use capability::{{iwasm_command, node_command}};
use ts2wasm_shared::test_helpers::temp_wasm_path;

fn assert_fixture_matches_node(fixture: &str) {{
    let fixture_path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join(fixture);
    let output = temp_wasm_path(fixture);

    let node = node_command().arg(&fixture_path).output().unwrap();
    assert!(
        node.status.success(),
        "node failed for {{fixture}}\nstdout:\n{{}}\nstderr:\n{{}}",
        String::from_utf8_lossy(&node.stdout),
        String::from_utf8_lossy(&node.stderr)
    );

    let build = Command::new(env!("CARGO_BIN_EXE_ts2wasm"))
        .arg("build")
        .arg(&fixture_path)
        .arg("-o")
        .arg(&output)
        .output()
        .unwrap();
    assert!(
        build.status.success(),
        "build failed for {{fixture}}\nstdout:\n{{}}\nstderr:\n{{}}",
        String::from_utf8_lossy(&build.stdout),
        String::from_utf8_lossy(&build.stderr)
    );

    let iwasm = run_iwasm_with_timeout_duration(iwasm_command().arg(&output), Duration::from_secs(5))
        .unwrap_or_else(|e| panic!("iwasm execution failed for {{fixture}}: {{e}}"));
    assert!(
        !iwasm.timed_out,
        "iwasm timed out for {{fixture}}\nstdout:\n{{}}\nstderr:\n{{}}",
        String::from_utf8_lossy(&iwasm.output.stdout),
        String::from_utf8_lossy(&iwasm.output.stderr)
    );
    assert!(
        iwasm.output.status.success(),
        "iwasm failed for {{fixture}}\nstdout:\n{{}}\nstderr:\n{{}}",
        String::from_utf8_lossy(&iwasm.output.stdout),
        String::from_utf8_lossy(&iwasm.output.stderr)
    );

    let node_stdout = String::from_utf8_lossy(&node.stdout);
    let iwasm_stdout = String::from_utf8_lossy(&iwasm.output.stdout);
    assert_eq!(
        iwasm_stdout, node_stdout,
        "stdout mismatch for {{fixture}}\n  node:  {{:?}}\n  iwasm: {{:?}}",
        node_stdout, iwasm_stdout
    );
}}

"""

FIXTURE_TEMPLATE = r"""#[test]
fn auto_diff_{test_name}() {{
    assert_fixture_matches_node("fixtures/{dir}/{file}");
}}

"""


def load_catalog(catalog_path: str) -> list[tuple[str, str]]:
    """Load fixture catalog and return list of (dir_name, filename)."""
    import yaml

    path = Path(catalog_path)
    if not path.exists():
        raise FileNotFoundError(f"catalog not found: {catalog_path}")

    with open(path) as f:
        catalog = yaml.safe_load(f)

    if not isinstance(catalog, dict):
        raise ValueError("catalog must be a top-level mapping")

    fixtures = []
    directories = catalog.get("directories", {})
    if not isinstance(directories, dict):
        raise ValueError("catalog.directories must be a dict")

    for dir_name, dir_entry in directories.items():
        if not isinstance(dir_entry, dict):
            continue
        fixture_list = dir_entry.get("fixtures", [])
        if not isinstance(fixture_list, list):
            continue
        for fixture in fixture_list:
            if isinstance(fixture, str):
                fname = fixture
            elif isinstance(fixture, dict):
                fname = fixture.get("name", "")
            else:
                continue
            if not fname:
                continue
            fixtures.append((dir_name, fname))

    fixtures.sort()
    return fixtures


def fixture_to_test_name(dir_name: str, fname: str) -> str:
    """Convert fixture path to a valid Rust test identifier."""
    name = f"{dir_name}_{fname}"
    # Replace non-alphanumeric chars with underscores
    name = "".join(c if c.isalnum() else "_" for c in name)
    # Collapse multiple underscores
    while "__" in name:
        name = name.replace("__", "_")
    # Strip leading/trailing underscores
    name = name.strip("_")
    # Ensure it's not empty
    if not name:
        name = "fixture"
    return name


def generate_rust_tests(fixtures: list[tuple[str, str]]) -> str:
    """Generate Rust test code for the given fixtures."""
    lines = []
    lines.append(RUST_HEADER.format(
        timestamp=__import__("datetime").datetime.now().isoformat(),
        total=len(fixtures),
    ))

    for dir_name, fname in fixtures:
        test_name = fixture_to_test_name(dir_name, fname)
        lines.append(FIXTURE_TEMPLATE.format(
            test_name=test_name,
            dir=dir_name,
            file=fname,
        ))

    return "".join(lines)


def print_jsonl_output(fixtures: list[tuple[str, str]]):
    """Print fixture list as JSONL for downstream consumption."""
    for dir_name, fname in fixtures:
        record = {
            "suite": f"fixtures/{dir_name}",
            "case": fname,
            "target": "wasm32-wasi",
            "generated": True,
            "source": "auto_diff",
        }
        print(json.dumps(record, ensure_ascii=False))


def main():
    parser = argparse.ArgumentParser(
        description="Generate Rust differential test code from fixture catalog",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--output",
        type=str,
        default=str(DEFAULT_OUTPUT),
        help=f"Output Rust file path (default: {DEFAULT_OUTPUT})",
    )
    parser.add_argument(
        "--sample",
        type=int,
        default=0,
        help="Generate tests for first N fixtures only (0 = all)",
    )
    parser.add_argument(
        "--jsonl",
        action="store_true",
        default=False,
        help="Output fixture list as JSONL instead of generating Rust code",
    )
    parser.add_argument(
        "--catalog",
        type=str,
        default=str(CATALOG_PATH),
        help="Path to fixture catalog YAML (default: fixtures/catalog.yaml)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        default=False,
        help="Print generated code to stdout instead of writing to file",
    )
    args = parser.parse_args()

    # Load fixtures
    try:
        fixtures = load_catalog(args.catalog)
    except (FileNotFoundError, ValueError, ImportError) as e:
        print(f"generate-differential-tests: catalog error: {e}", file=sys.stderr)
        sys.exit(1)

    sample = args.sample
    if sample > 0:
        fixtures = fixtures[:sample]

    print(
        f"generate-differential-tests: loaded {len(fixtures)} fixtures from catalog",
        file=sys.stderr,
    )

    if args.jsonl:
        print_jsonl_output(fixtures)
        return

    # Generate Rust test code
    rust_code = generate_rust_tests(fixtures)

    if args.dry_run:
        print(rust_code)
        return

    # Write to output file
    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w") as f:
        f.write(rust_code)

    print(
        f"generate-differential-tests: wrote {len(rust_code)} bytes to {output_path}",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main()
