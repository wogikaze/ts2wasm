#!/usr/bin/env bash
set -euo pipefail

_ts2wasm_entry_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=../lib/common.sh
source "${_ts2wasm_entry_dir}/../lib/common.sh"
cd "$TS2WASM_REPO_ROOT"
repo_root="$TS2WASM_REPO_ROOT"

if ts2wasm_parse_common_args "$@"; then
  :
else
  case $? in
    1)
      ts2wasm_usage "scripts/gen/coverage-matrix.sh" \
        "Reads current executed counts from artifacts/coverage/reference-coverage-matrix.md, increases per-suite limits by fixed step each run (ramp-up), re-runs reference coverage sampling for each suite, and rewrites the coverage table rows."
      exit 0
      ;;
    2)
      ts2wasm_usage "scripts/gen/coverage-matrix.sh" \
        "Reads current executed counts from artifacts/coverage/reference-coverage-matrix.md and rewrites the coverage table rows."
      exit 1
      ;;
  esac
fi

check_mode="$TS2WASM_CHECK_MODE"

doc_file="artifacts/coverage/reference-coverage-matrix.md"
if [[ ! -f "$doc_file" ]]; then
  mkdir -p "$(dirname "$doc_file")"
  cat > "$doc_file" <<'EOF'
# Reference Coverage Matrix (generated)

Generated by scripts/gen/coverage-matrix.sh.
Do not edit manually.

<!-- coverage-table:start -->
| suite | denominator | executed | build_coverage% | semantic_coverage% | build_pass | semantic_pass | fail | unsupported | blocked | skip-with-reason | unsupported (DiagCode breakdown) | status | evidence |
|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|---|---|
| test262 | 0 | 0 | 0.00 | 0.00 | 0 | 0 | 0 | 0 | 0 | 0 | - | in-progress | `scripts/run/reference-coverage.sh test262 --limit 0` |
| TypeScript compiler cases | 0 | 0 | 0.00 | 0.00 | 0 | 0 | 0 | 0 | 0 | 0 | - | in-progress | `scripts/run/reference-coverage.sh tsc --limit 0` |
| typescript-go testdata | 0 | 0 | 0.00 | 0.00 | 0 | 0 | 0 | 0 | 0 | 0 | - | in-progress | `scripts/run/reference-coverage.sh tsgo --limit 0` |
<!-- coverage-table:end -->
EOF
fi

extract_current_executed() {
  local suite_name="$1"
  local value
  value="$({
    grep -F "| $suite_name |" "$doc_file" || true
  } | head -n 1 | awk -F'|' '{gsub(/ /, "", $4); print $4}')"
  if [[ -z "$value" ]]; then
    echo 0
  else
    echo "$value"
  fi
}

next_limit() {
  local current="$1"
  local step="$2"
  local denominator="$3"
  local proposed=$((current + step))
  if [[ "$proposed" -lt "$step" ]]; then
    proposed="$step"
  fi
  if [[ "$proposed" -gt "$denominator" ]]; then
    proposed="$denominator"
  fi
  echo "$proposed"
}

parse_output_value() {
  local key="$1"
  local blob="$2"
  printf '%s\n' "$blob" | awk -F'=' -v k="$key" '$1==k {print substr($0, index($0,$2)); exit}'
}

run_suite() {
  local suite_key="$1"
  local suite_name="$2"
  local step="$3"

  local current
  current="$(extract_current_executed "$suite_name")"

  local baseline_out
  baseline_out="$("${repo_root}/scripts/run/reference-coverage.sh" "$suite_key" --limit 1)"
  local denominator
  denominator="$(parse_output_value denominator "$baseline_out")"

  local limit
  if [[ "$check_mode" -eq 1 ]]; then
    limit="$current"
    if [[ "$limit" -le 0 ]]; then
      limit="$step"
    fi
  else
    limit="$(next_limit "$current" "$step" "$denominator")"
  fi

  local out
  out="$("${repo_root}/scripts/run/reference-coverage.sh" "$suite_key" --limit "$limit")"

  local build_coverage semantic_coverage build_pass semantic_pass fail unsupported blocked skip diag
  build_coverage="$(parse_output_value coverage_percent "$out")"
  semantic_coverage="$(parse_output_value semantic_coverage_percent "$out")"
  build_pass="$(parse_output_value build_pass "$out")"
  semantic_pass="$(parse_output_value semantic_pass "$out")"
  fail="$(parse_output_value fail "$out")"
  unsupported="$(parse_output_value unsupported "$out")"
  blocked="$(parse_output_value blocked "$out")"
  skip="$(parse_output_value skip_with_reason "$out")"
  diag="$(parse_output_value unsupported_diagcodes "$out")"

  if [[ -z "$diag" ]]; then
    diag="-"
  fi

  printf '| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | in-progress | `scripts/run/reference-coverage.sh %s --limit %s` |\n' \
    "$suite_name" "$denominator" "$limit" "$build_coverage" "$semantic_coverage" "$build_pass" "$semantic_pass" "$fail" "$unsupported" "$blocked" "$skip" "$diag" "$suite_key" "$limit"
}

row_test262="$(run_suite test262 "test262" 50)"
row_tsc="$(run_suite tsc "TypeScript compiler cases" 30)"
row_tsgo="$(run_suite tsgo "typescript-go testdata" 20)"

tmp_file="$(mktemp /tmp/ts2wasm-cov-matrix-XXXXXX.md)"
trap 'rm -f "$tmp_file"' EXIT
awk -v r1="$row_test262" -v r2="$row_tsc" -v r3="$row_tsgo" '
  BEGIN {state=0}
  /<!-- coverage-table:start -->/ {
    print
    print "| suite | denominator | executed | build_coverage% | semantic_coverage% | build_pass | semantic_pass | fail | unsupported | blocked | skip-with-reason | unsupported (DiagCode breakdown) | status | evidence |"
    print "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|---|---|"
    print r1
    print r2
    print r3
    state=1
    next
  }
  /<!-- coverage-table:end -->/ {
    print
    state=0
    next
  }
  state==0 {print}
' "$doc_file" >"$tmp_file"

if [[ "$check_mode" -eq 1 ]]; then
  if ! cmp -s "$doc_file" "$tmp_file"; then
    ts2wasm_log "coverage matrix is stale; run scripts/gen/coverage-matrix.sh and commit $doc_file"
    diff -u "$doc_file" "$tmp_file" >&2 || true
    exit 1
  fi
  ts2wasm_log "coverage matrix OK (up to date)"
else
  mv "$tmp_file" "$doc_file"
  trap - EXIT
  ts2wasm_log "updated $doc_file"
fi
